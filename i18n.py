def normalize_lang(value):
    if not value:
        return "en"
    value = str(value).lower()
    if value.startswith("hi"):
        return "hi"
    return "en"


def translate(lang, key, default=None):
    lang = normalize_lang(lang)
    table = STRINGS.get(lang) or STRINGS["en"]
    if key in table:
        return table[key]
    return STRINGS["en"].get(key, default if default is not None else key)
